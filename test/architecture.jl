const RANK_OF_MODULE = Dict("Model" => 1, "Texts" => 2, "Catalogue" => 3, "ConfigIO" => 4,
                            "Engine" => 5, "Render" => 6, "Orchestration" => 7, "CLI" => 8)

# The tree being replaced. This number only falls; a commit that raises it fails here, which is what
# makes "two machines in one tree" a measured state rather than a feeling.
const LEGACY_CEILING = 18

# The table as the document holds it: one named tuple per row, the leading `**name**` and six cells.
function table_rows(path)
    rows = NamedTuple[]
    for line in readlines(path)
        startswith(line, "| **") || continue
        cells = strip.(split(strip(line, ['|', ' ']), "|"))
        length(cells) == 7 || continue
        push!(rows, (name = String(cells[1]), purpose = String(cells[2]), intention = uppercase(String(cells[3])),
                     decided_by = String(cells[4]), fixed_by = String(cells[5]),
                     when = String(cells[6]), ends = String(cells[7])))
    end
    return rows
end

decider_words(d) = d === G.Model.Decider.PROGRAM ? "A program" :
                   d === G.Model.Decider.FAILING_TEST ? "An agent proposes, a program decides" : "An agent"

fixer_words(f) = f === G.Model.Fixer.ORDINARY_WORK ? "Whoever ran it, as ordinary work" :
                 f === G.Model.Fixer.DOCUMENTATION_FIXER ? "Documentation fixer" :
                 f === G.Model.Fixer.CODE_FIXER ? "Code fixer" :
                 f === G.Model.Fixer.REGENERATE ? "Regenerated by `gbg sync`, `gbg bump` or `gbg release`" : "Owner only"

legacy_files() = sort([relpath(joinpath(r, f), TOOL) for (r, _, fs) in walkdir(joinpath(TOOL, "src"))
                       for f in fs if endswith(f, ".jl") && !haskey(LAYERS, relpath(joinpath(r, f), TOOL))])

@testset "the module order, the legacy count, and self-application" begin
    @testset "every source file is in one tree or the other" begin
        all_jl = [relpath(joinpath(r, f), TOOL) for (r, _, fs) in walkdir(joinpath(TOOL, "src"))
                  for f in fs if endswith(f, ".jl")]
        for f in all_jl
            @test haskey(LAYERS, f) || f in legacy_files()
        end
        @test !isempty(LAYERS)
    end

    @testset "the legacy tree only shrinks" begin
        n = length(legacy_files())
        @test n <= LEGACY_CEILING
        # and the ceiling is not left far above the truth, which would make it stop measuring anything
        @test n >= LEGACY_CEILING - 8
    end

    @testset "no file of the new tree reaches a module above it" begin
        for (file, rank) in LAYERS
            text = read(joinpath(TOOL, file), String)
            for (mod, r) in RANK_OF_MODULE
                r <= rank && continue
                @test !occursin(Regex("\\b" * mod * "\\.[A-Za-z_]"), text)
            end
        end
    end

    # The rule the science packages depend on: what runs inside a consumer's build or test may not read
    # review state, because CI and a fresh clone must give the same answer. It is checked over the whole
    # tree, old and new, since the extension and the harness are what a consumer actually runs.
    @testset "nothing a build or a test runs reads review state" begin
        for f in ("ext/GBGCodingToolsDocumenterExt.jl", "src/TestHarness.jl", "src/DocLints.jl")
            text = read(joinpath(TOOL, f), String)
            for forbidden in (".gbg/runs", ".gbg/rounds", "questions.json", "settled.jl", "Orchestration.")
                @test !occursin(forbidden, text)
            end
        end
    end

    # The design's §3 table and the values are ONE table. Every cell is compared, so a purpose reworded in
    # the document without the value moving — or the other way about — fails here. The three axes are
    # compared as a set as well: two rows with the same intention, decider and fixer would be two names
    # for one thing, which is what the table exists to prevent.
    @testset "the instrument table is the document's table" begin
        rows = table_rows(joinpath(TOOL, "docs", "ARCHITECTURE.md"))
        @test length(rows) == 7                                   # three always-on, three instruments, one future
        values = vcat(G.Catalogue.ALWAYS_ON, G.Catalogue.INSTRUMENTS)
        @test length(values) == 6                                 # the leak scan's row is marked future
        for (row, v) in zip(rows[1:6], values)
            @test row.purpose == v.purpose
            @test row.intention == uppercase(replace(string(v.intention), "_" => " "))
            @test row.decided_by == decider_words(v.decider)
            @test row.fixed_by == fixer_words(v.fixer)
            @test row.when == v.when
            @test row.ends == (v isa G.Model.AlwaysOn ? "—" : v.ends)
        end
        @test occursin("future", lowercase(rows[7].name))          # and the seventh says it is not built
        @test length(unique(G.Catalogue.axes.(values))) == length(values)
    end

    # Self-application, three ways. Not the fourth the plan named — that this package's docs/make.jl call
    # `Documenter.makedocs` plainly — because the owner ruled on 2026-09-15 that the DETERMINISTIC checks
    # keep working here (rogue formatting, uniform docstring structure) while the domain-specific parts
    # stay off. The wrapper is that deterministic half, so it stays; what must not come back early is an
    # instrument.
    @testset "this package is its own last consumer, not its first" begin
        cfg = TOML.parsefile(joinpath(TOOL, ".gbg", "config.toml"))
        @test !haskey(cfg, "instruments")                               # no instrument is configured here
        skills = joinpath(TOOL, ".claude", "skills")
        # A skill per instrument that applies, and NOT ONE MORE. `gbg-doctor` outlived the doctor by a
        # day: nothing rendered it after `Sync` went, and it told a session to run `gbg doctor`,
        # `gbg round prepare` and `/check-docs`, all three of which were deleted. Every skill here is
        # written from the instrument's own value, so it cannot outlive it the same way.
        here = G.ConfigIO.read_config(TOOL)
        applies = [i.id for i in G.Catalogue.INSTRUMENTS if G.Engine.Checks.applies(here, i.id)]
        @test sort(readdir(skills)) == sort([basename(dirname(G.Render.skill_path(id))) for id in applies])
        # The review is switched off HERE until Phase 8: the tool reviews itself last, and a skill for
        # it would be a command that refuses to start.
        @test !(:documentation_review in applies)
        @test !isdir(joinpath(skills, "documentation-review"))
        @test !isdir(joinpath(TOOL, ".gbg", "runs"))                    # no run has been recorded here
        @test occursin("GBGCodingTools.makedocs", read(joinpath(TOOL, "docs", "make.jl"), String))
    end

    # §5.2 of the design prints the types as Julia. Prose that restates Julia values is compared with
    # them by a test, or the two drift and the design becomes a description of something else: the
    # enums lost a value and gained one during this phase, and nothing but this would have said so.
    @testset "the design's types are the types" begin
        text = read(joinpath(TOOL, "docs", "ARCHITECTURE.md"), String)
        section = match(r"### 5\.2 Types(.*?)\n### ", text; ) === nothing ?
                  split(split(text, "### 5.2 Types")[2], "\n## ")[1] :
                  match(r"### 5\.2 Types(.*?)\n### "s, text).captures[1]

        # every enum the design prints, with exactly the values it prints
        enums = collect(eachmatch(r"module (\w+);\s*@enum T ([^;]+);\s*end", section))
        @test length(enums) >= 10
        for m in enums
            occursin("…", m.captures[2]) && continue     # the sentence that shows the FORM, not an enum
            name, values = Symbol(m.captures[1]), Symbol.(split(strip(m.captures[2])))
            @test isdefined(G.Model, name)
            mod = getfield(G.Model, name)
            @test collect(Symbol.(instances(mod.T))) == values
        end

        # every struct it prints, with the fields it names on them
        for m in eachmatch(r"(?:Base\.@kwdef )?struct (\w+)", section)
            name = Symbol(m.captures[1])
            @test isdefined(G.Model, name)
        end
        for (name, fields) in (:Location => [:file, :node, :text, :line, :found],
                               :FindingDraft => [:rule, :locations, :claim, :evidence, :fix, :maybe_code],
                               :Finding => [:id, :source, :decider, :draft],
                               :Option => [:label, :consequence, :recommended],
                               :Switch => [:target, :reason, :files])
            @test collect(fieldnames(getfield(G.Model, name))) == fields
        end

        # and the design does not print a type that no longer exists
        for m in eachmatch(r"^(?:Base\.@kwdef )?struct (\w+)"m, section)
            @test isdefined(G.Model, Symbol(m.captures[1]))
        end
    end

    # The fleet has ONE home. It was named in two files until 2026-09-18 — the roster as `[[consumer]]`
    # rows in `fleet.toml`, the sites as a second list in `Rules/pages.jl` — with nothing comparing them,
    # and a rename applied to one alone fails SILENTLY IN BOTH DIRECTIONS: a package writing the new name
    # gets no finding from `RULE.DOC.SIBLING_LINK`, which has nothing to say about a name it does not
    # hold, and a package writing the old name is sent to a URL that 404s. What is held here is that the
    # second list has not grown back, which is the only way the divergence can return.
    @testset "the fleet is named once" begin
        sites = Dict(G.Catalogue.Pages.SIBLING_SITES.default)
        @test sort([c.name for c in G.Catalogue.FLEET]) == sort(collect(keys(sites)))
        for c in G.Catalogue.FLEET
            @test sites[c.name] == G.Catalogue.site_of(c.github)       # derived, never written twice
            @test occursin("/", c.github)                              # owner/repo, which site_of needs
        end
        # `fleet.toml` carries the sweep state a verb writes, and no roster.
        @test !haskey(TOML.parsefile(joinpath(TOOL, "fleet.toml")), "consumer")
    end
end
